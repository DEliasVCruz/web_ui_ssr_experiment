/**
 * wrap-jsonschema.ts — post-processes `buf generate` output (runs right after it,
 * via the root `generate` script).
 *
 * protoc-gen-jsonschema (see buf.gen.yaml) emits the proto-derived JSON Schema —
 * carrying the buf.validate string `min_len`/`max_len` as `minLength`/`maxLength`
 * — as plain `*.jsonschema.json` files. Those are data, not TS, so @ark/json-schema
 * cannot infer literal bounds from them. This wrapper re-emits the request schemas
 * the frontend form consumes as TS modules that export the schema `as const`, so
 * jsonSchemaToType gets literal inference over the exact numeric bounds.
 *
 * Scope: CreateTodoRequest + UpdateTodoRequest only. Both are flat string/bool
 * messages (no message-typed fields), so their schemas contain no `$ref` and
 * jsonSchemaToType consumes them directly. Message-typed schemas (Todo, the
 * responses) are `$ref`-heavy; wrapping those is intentionally out of scope
 * because the form never validates them.
 *
 * Output lands under packages/rpc/gen (gitignored, regenerated per checkout) and
 * is consumed via `@web-ui-poc/rpc/gen/jsonschema/schemas`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// proto message name -> exported const name. `as const` keeps the tuple literal.
const MESSAGES = [
	{ proto: "todo.v1.CreateTodoRequest", constName: "createTodoRequestSchema" },
	{ proto: "todo.v1.UpdateTodoRequest", constName: "updateTodoRequestSchema" },
] as const;

const genDir = join(import.meta.dirname, "..", "packages", "rpc", "gen", "jsonschema");

const header = [
	"// @generated by scripts/wrap-jsonschema.ts — DO NOT EDIT.",
	"// Regenerated by `bun run generate` from the proto-derived *.jsonschema.json,",
	"// which in turn carry the proto's buf.validate min_len/max_len as minLength/maxLength.",
	"// Exported `as const` so @ark/json-schema's jsonSchemaToType infers the literal bounds.",
	"",
	"",
].join("\n");

const modules = MESSAGES.map(({ proto, constName }) => {
	const json = readFileSync(join(genDir, `${proto}.jsonschema.json`), "utf8").trimEnd();
	return `export const ${constName} = ${json} as const;`;
});

writeFileSync(join(genDir, "schemas.ts"), `${header}${modules.join("\n\n")}\n`);
