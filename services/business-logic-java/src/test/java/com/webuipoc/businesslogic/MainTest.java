package com.webuipoc.businesslogic;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.helidon.webserver.WebServer;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import org.junit.jupiter.api.Test;

class MainTest {

    @Test
    void healthEndpointReturnsSameJsonShapeAsBunService() throws Exception {
        WebServer server = WebServer.builder()
                .port(0)
                .routing(Main::routing)
                .build()
                .start();
        try (HttpClient client = HttpClient.newHttpClient()) {
            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create("http://localhost:" + server.port() + "/health"))
                    .GET()
                    .build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            assertEquals(200, response.statusCode());
            assertEquals("{\"status\":\"ok\"}", response.body());
            assertEquals("application/json",
                    response.headers().firstValue("content-type").orElse(""));
        } finally {
            server.stop();
        }
    }

    @Test
    void portResolutionMirrorsBunService() {
        assertEquals(3001, Main.resolvePort(null));
        assertEquals(3001, Main.resolvePort(""));
        assertEquals(3001, Main.resolvePort("not-a-number"));
        assertEquals(3001, Main.resolvePort("0"));
        assertEquals(8080, Main.resolvePort("8080"));
    }

    @Test
    void generatedGrpcStubsAndProtobufMessagesWork() {
        // Stubs generated by buf (protoc-gen-grpc-java) are on the compile path.
        assertEquals("todo.v1.TodoService", todo.v1.TodoServiceGrpc.SERVICE_NAME);
        assertEquals(5, todo.v1.TodoServiceGrpc.getServiceDescriptor().getMethods().size());

        // Editions-2023 gencode cooperates with the protobuf-java runtime,
        // including explicit field presence on UpdateTodoRequest.title.
        todo.v1.TodoOuterClass.UpdateTodoRequest request =
                todo.v1.TodoOuterClass.UpdateTodoRequest.newBuilder()
                        .setId("todo-1")
                        .setTitle("renamed")
                        .build();
        assertTrue(request.hasTitle());
        assertEquals("renamed", request.getTitle());
    }
}
